#!/usr/bin/env python3
"""Rebuild docs/ai-workflow/SUMMARY.md from the log entries' front matter (stdlib only)."""
from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs" / "ai-workflow"


def front_matter(text: str) -> dict[str, str]:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.split("#", 1)[0].strip().strip('"')
    return out


def as_int(v: str | None) -> int:
    try:
        return int(float(v or 0))
    except ValueError:
        return 0


def main() -> None:
    entries = []
    for path in sorted((DOCS / "log").rglob("*.md")):
        text = path.read_text(encoding="utf-8")
        fm = front_matter(text)
        if not fm:
            continue
        title = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), path.stem)
        entries.append((fm, title, path.relative_to(DOCS).as_posix()))
    entries.sort(key=lambda e: e[0].get("date", ""))

    tools = Counter(e[0].get("tool", "?") for e in entries)
    phases = Counter(e[0].get("phase", "?") for e in entries)
    outcomes = Counter(e[0].get("outcome", "?") for e in entries)
    ai_min = sum(as_int(e[0].get("minutes_ai")) for e in entries)
    manual_min = sum(as_int(e[0].get("minutes_manual_est")) for e in entries)

    def table(counter: Counter, head: str) -> str:
        rows = "\n".join(f"| {k} | {v} |" for k, v in counter.most_common())
        return f"| {head} | Entries |\n|---|---|\n{rows}\n"

    lines = [
        "# AI workflow summary",
        "",
        "_Generated by `scripts/ai-log/summarize.py`. Do not edit by hand._",
        "",
        f"- Entries: **{len(entries)}**",
        f"- Time with AI: **{ai_min / 60:.1f} h** vs estimated by hand: **{manual_min / 60:.1f} h**"
        + (f" (≈ {manual_min / ai_min:.1f}× faster)" if ai_min else ""),
        f"- Outcome: {', '.join(f'{k} {v}' for k, v in outcomes.most_common()) or '-'}",
        "",
        "## By tool", "", table(tools, "Tool"),
        "## By phase", "", table(phases, "Phase"),
        "## Highlights", "",
    ]
    hl = [e for e in entries if e[0].get("highlight", "").lower() == "true"]
    lines += [f"- {fm.get('date')} · {fm.get('tool')} · [{t}]({p})" for fm, t, p in hl] or ["- none yet"]
    lines += ["", "## Timeline", "", "| Date | Tool | Issue | Outcome | Entry |", "|---|---|---|---|---|"]
    lines += [f"| {fm.get('date')} | {fm.get('tool')} | {fm.get('issue')} | {fm.get('outcome')} | [{t}]({p}) |"
              for fm, t, p in entries]
    (DOCS / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"SUMMARY.md: {len(entries)} entries")


if __name__ == "__main__":
    main()
